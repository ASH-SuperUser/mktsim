def ex_cli_repl() -> None:
    h3("CLI 6 — the REPL, same flow interactively")
    lines.append("Start with `mktsim`, then:\n```text")
    cmds = ["use basic_id_sim_1", "set nums 20", "set initial_price 100",
            "set seed 7", "run", "show", "quit"]
    proc = cli(stdin="\n".join(cmds) + "\n")
    assert proc.returncode == 0, proc.stderr
    # Piped stdin is not echoed, so rebuild the transcript: the banner plus
    # each typed command followed by its real captured response.
    chunks = proc.stdout.split("sim> ")
    assert len(chunks) == len(cmds) + 1, repr(proc.stdout)  # banner + one prompt per command
    assert chunks[0].startswith("share-market simulator")
    assert "using basic_interaday.basic_id_sim_1" in chunks[1]
    transcript = [chunks[0].rstrip()]
    for cmd, resp in zip(cmds, chunks[1:]):
        transcript.append(f"sim> {cmd}\n{resp.rstrip()}")
    lines.append("\n".join(transcript).strip() + "\n```\n")


