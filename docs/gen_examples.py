"""Generate docs/examples.md from REAL executed output.

Every snippet below actually runs (library calls + CLI subprocesses) with
fixed seeds, asserts its invariants, and embeds the captured output, so the
examples page can never drift from the code. Re-run with:

    .\\venv\\Scripts\\python.exe docs/gen_examples.py
"""

from __future__ import annotations

import os
import statistics
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from mktsim import (  # noqa: E402
    adv_id_sim_1,
    adv_id_sim_2,
    bars_ex_to_csv,
    bars_to_csv,
    basic_id_sim_1,
    basic_id_sim_2,
    basic_id_sim_3,
    basic_id_sim_4,
    simulate_ohlcv,
    ticks_to_csv,
    ticks_to_ohlcv,
)

OUT = ROOT / "docs" / "examples.md"
TMP = Path(tempfile.mkdtemp(prefix="mktsim_examples_"))
PY = sys.executable  # the venv interpreter (nothing global)


def cli(*args: str, stdin: str | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(
        [PY, "-m", "mktsim.cli", *args],
        capture_output=True, text=True, cwd=str(ROOT), input=stdin,
    )


def short(text: str) -> str:
    """Strip the machine-specific temp dir so docs stay portable."""
    return text.replace(str(TMP) + os.sep, "").replace(str(TMP), ".")


def pct(a: float, b: float) -> float:
    return (b - a) / a * 100.0


lines: list[str] = []


def h1(t: str) -> None:
    lines.append(f"# {t}\n")


def h2(t: str) -> None:
    lines.append(f"## {t}\n")


def h3(t: str) -> None:
    lines.append(f"### {t}\n")


def prologue() -> None:
    lines.append(
        "<!-- AUTO-GENERATED by docs/gen_examples.py -- DO NOT EDIT BY HAND. -->\n"
        "Every output block on this page was produced by actually running the\n"
        "code shown (fixed seeds), so examples never drift from the library.\n"
        "Regenerate with `.\\venv\\Scripts\\python.exe docs/gen_examples.py`.\n"
    )


# ============================================================ library
def ex_basic_path() -> None:
    h3("Library 1 — your first price path")
    lines.append("```python\nfrom mktsim import basic_id_sim_1\n\npath = basic_id_sim_1(375, 100.0, seed=1)\n```\n")
    path = basic_id_sim_1(375, 100.0, seed=1)
    assert len(path) == 375 and path[0] == 100.0 and all(p > 0 for p in path)
    lines.append("```text\n" + (
        f"ticks=375 start={path[0]:.2f} end={path[-1]:.2f} "
        f"min={min(path):.2f} max={max(path):.2f} "
        f"return={pct(path[0], path[-1]):+.2f}%\n```\n"
    ))


def ex_profitability() -> None:
    h3("Library 2 — profitability biases the flow, not the fate")
    lines.append(
        "```python\nfrom mktsim import basic_id_sim_1\n\n"
        "for profit in (1.0, 0.0, -1.0):\n"
        "    ups = sum(1 for s in range(60)\n"
        "              if basic_id_sim_1(200, 100.0, profit, seed=s)[-1] >= 100.0)\n"
        "    print(profit, f\"{ups}/60 up\")\n```\n"
    )
    out = []
    for profit in (1.0, 0.0, -1.0):
        ups = sum(1 for s in range(60) if basic_id_sim_1(200, 100.0, profit, seed=s)[-1] >= 100.0)
        out.append(f"{profit} {ups}/60 up")
    assert "1.0 47/60" in out[0] and "0.0 31/60" in out[1] and "-1.0 12/60" in out[2]
    lines.append("```text\n" + "\n".join(out) + "\n```\n")
    lines.append(
        "`+1` finishes up most of the time, `-1` mostly down, `0.0` is a\n"
        "coin flip — but single paths can always go against the bias.\n"
    )


def ex_volumes() -> None:
    h3("Library 3 — prices plus per-tick volumes")
    lines.append(
        "```python\nfrom mktsim import basic_id_sim_1\n\n"
        "prices, volumes = basic_id_sim_1(10, 100.0, seed=7, return_volumes=True)\n"
        "for t, (p, v) in enumerate(zip(prices, volumes)):\n"
        "    print(f\"tick={t} price={p:.2f} volume={v}\")\n```\n"
    )
    prices, volumes = basic_id_sim_1(10, 100.0, seed=7, return_volumes=True)
    assert len(prices) == len(volumes) == 10 and volumes[0] == 0
    assert prices == basic_id_sim_1(10, 100.0, seed=7)  # flag changes nothing
    lines.append("```text\n" + "\n".join(
        f"tick={t} price={p:.2f} volume={v}" for t, (p, v) in enumerate(zip(prices, volumes))
    ) + f"\ntotal volume={sum(volumes)}\n```\n")


def ex_ohlcv() -> None:
    h3("Library 4 — ticks into OHLCV bars")
    lines.append(
        "```python\nfrom mktsim import basic_id_sim_1, ticks_to_ohlcv\n\n"
        "prices, volumes = basic_id_sim_1(20, 100.0, seed=7, return_volumes=True)\n"
        "for b in ticks_to_ohlcv(prices, volumes, bars=4):\n"
        "    print(b)\n```\n"
    )
    prices, volumes = basic_id_sim_1(20, 100.0, seed=7, return_volumes=True)
    bars = ticks_to_ohlcv(prices, volumes, bars=4)
    assert len(bars) == 4 and sum(b["volume"] for b in bars) == sum(volumes)
    assert bars[0]["open"] == prices[0] and bars[-1]["close"] == prices[-1]
    lines.append("```text\n" + "\n".join(repr(b) for b in bars) + "\n```\n")


def ex_csv_api() -> None:
    h3("Library 5 — CSV export from Python")
    lines.append(
        "```python\nfrom mktsim import basic_id_sim_1, bars_to_csv, simulate_ohlcv, ticks_to_csv\n\n"
        "prices, volumes = basic_id_sim_1(20, 100.0, seed=7, return_volumes=True)\n"
        "ticks_to_csv(prices, volumes, \"ticks.csv\")\n"
        "bars_to_csv(simulate_ohlcv(basic_id_sim_1, 20, 100.0, 0.0, seed=7, bars=4), \"bars.csv\")\n```\n"
    )
    prices, volumes = basic_id_sim_1(20, 100.0, seed=7, return_volumes=True)
    tp = TMP / "ticks.csv"
    bp = TMP / "bars.csv"
    ticks_to_csv(prices, volumes, str(tp))
    bars_to_csv(simulate_ohlcv(basic_id_sim_1, 20, 100.0, 0.0, seed=7, bars=4), str(bp))
    tick_lines = tp.read_text(encoding="utf-8").splitlines()
    bar_lines = bp.read_text(encoding="utf-8").splitlines()
    assert tick_lines[0] == "tick,price,volume" and len(tick_lines) == 21
    assert bar_lines[0] == "bar,open,high,low,close,volume" and len(bar_lines) == 5
    lines.append("`ticks.csv` (head):\n```csv\n" + "\n".join(tick_lines[:5]) + "\n```\n")
    lines.append("`bars.csv` (full):\n```csv\n" + "\n".join(bar_lines) + "\n```\n")


def ex_bands() -> None:
    h3("Library 6 — growth bands cap every step")
    lines.append(
        "```python\nfrom mktsim import basic_id_sim_2\n\n"
        "path = basic_id_sim_2(120, 50.0, 0.5, max_growth=0.01, min_growth=-0.01, seed=3)\n"
        "steps = [path[i] / path[i - 1] - 1 for i in range(1, len(path))]\n"
        "print(f\"worst step: {min(steps):+.4%} / {max(steps):+.4%}\")\n```\n"
    )
    path = basic_id_sim_2(120, 50.0, 0.5, 0.01, -0.01, seed=3)
    steps = [path[i] / path[i - 1] - 1 for i in range(1, len(path))]
    assert min(steps) >= -0.01 - 1e-4 and max(steps) <= 0.01 + 1e-4
    lines.append(f"```text\nworst step: {min(steps):+.4%} / {max(steps):+.4%}\n```\n")
    lines.append(f"No single tick moved more than ±1% (start={path[0]:.2f}, end={path[-1]:.2f}).\n")


