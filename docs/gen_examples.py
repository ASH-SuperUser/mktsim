def ex_adv_target() -> None:
    h3("Library 12 — steering the mean with target_pct")
    lines.append(
        "```python\nfrom mktsim import adv_id_sim_1\nimport statistics\n\n"
        "for target in (5.0, 0.0, -5.0):\n"
        "    ends = [adv_id_sim_1(150, 100.0, target, seed=s)[-1][\"close\"]\n"
        "            for s in range(15)]\n"
        "    print(f\"target={target:+.1f}% mean={statistics.mean(ends):.2f}\")\n```\n"
    )
    out = []
    means = []
    for target in (5.0, 0.0, -5.0):
        ends = [adv_id_sim_1(150, 100.0, target, seed=s)[-1]["close"] for s in range(15)]
        means.append(statistics.mean(ends))
        out.append(f"target={target:+.1f}% mean={means[-1]:.2f}")
    assert means[0] > means[1] > means[2]
    lines.append("```text\n" + "\n".join(out) + "\n```\n")


