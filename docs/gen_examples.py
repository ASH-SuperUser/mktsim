def ex_regimes() -> None:
    h3("Library 8 — day regimes change the character")
    lines.append(
        "```python\nfrom mktsim import basic_id_sim_3\n\n"
        "for regime in (\"normal\", \"trend\", \"range\", \"event\", \"calm\"):\n"
        "    path = basic_id_sim_3(200, 100.0, regime=regime, seed=7)\n"
        "    print(f\"{regime:6} end={path[-1]:7.2f} range={min(path):6.2f}-{max(path):6.2f}\")\n```\n"
    )
    out = []
    ends = []
    for regime in ("normal", "trend", "range", "event", "calm"):
        path = basic_id_sim_3(200, 100.0, regime=regime, seed=7)
        ends.append(path[-1])
        out.append(f"{regime:6} end={path[-1]:7.2f} range={min(path):6.2f}-{max(path):6.2f}")
    assert len(set(ends)) == 5  # regimes really differ
    lines.append("```text\n" + "\n".join(out) + "\n```\n")
    lines.append(
        "Same seed, five personalities — including `event` slamming the 10%\n"
        "lower circuit band (90.00) while `calm` barely leaves the open.\n"
    )


def ex_target() -> None:
    h3("Library 9 — targeting +5% on average")
    lines.append(
        "```python\nfrom mktsim import basic_id_sim_4\nimport statistics\n\n"
        "ends = [basic_id_sim_4(200, 100.0, 0.0, 0.05, seed=s)[-1] for s in range(40)]\n"
        "print(f\"mean={statistics.mean(ends):.2f} (target 105.00) \"\n"
        "      f\"worst={min(ends):.2f} best={max(ends):.2f}\")\n```\n"
    )
    ends = [basic_id_sim_4(200, 100.0, 0.0, 0.05, seed=s)[-1] for s in range(40)]
    assert abs(statistics.mean(ends) - 105.0) < 4.0
    assert min(ends) < 105.0 < max(ends)  # individuals scatter around the mean
    lines.append("```text\n" + (
        f"mean={statistics.mean(ends):.2f} (target 105.00) "
        f"worst={min(ends):.2f} best={max(ends):.2f}\n```\n"
    ))


